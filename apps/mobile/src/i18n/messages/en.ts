type DeepString<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends Record<string, unknown> | undefined | null
      ? DeepString<NonNullable<T[K]>>
      : T[K];
};

export type MessageTree = DeepString<typeof en>;
